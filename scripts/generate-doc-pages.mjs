/**
 * Turns the audits into Storybook pages.
 *
 * The reason this exists: the deployed Storybook is the artefact. Anyone
 * evaluating this system opens a URL — they do not clone the repo, and they
 * will never see `ARIA.md` or `DRIFT-REPORT.md` sitting next to the source.
 * A conformance report that lives only in a markdown file is a report written
 * for nobody.
 *
 * So the reports are generated into `docs/generated/` and rendered as pages,
 * from the same scripts that gate CI. Two consequences worth being explicit
 * about:
 *
 *   1. The numbers on the site are the numbers from the build. There is no
 *      hand-maintained "accessibility" page claiming conformance that nothing
 *      checks, which is the usual shape of that page.
 *   2. The failures are on the site too. 14 components currently fail their
 *      APG pattern, and the page says so. Publishing that is a choice: a
 *      design system that shows its own gaps is making a claim you can verify,
 *      and one that shows none is making a claim you cannot.
 *
 * `npm run docs:generate` runs before every Storybook build, and CI fails if
 * the committed output has drifted — same contract as the token artefacts.
 *
 *   node scripts/generate-doc-pages.mjs [--check]
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, 'docs/generated');
const CHECK = process.argv.includes('--check');

const run = (script, args = []) =>
  execFileSync('node', [resolve(ROOT, 'scripts', script), ...args], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
  });

/**
 * Markdown from the audits goes into MDX almost unchanged. Three fixes needed
 * (the third: a bare `<` in prose opens a JSX tag):
 * an MDX file cannot start with a level-one heading and also carry a `<Meta>`,
 * and `{` in prose is a JSX expression.
 */
function toMdx(title, markdown, preamble) {
  const body = markdown
    .split('\n')
    .slice(1) // the audit's own H1 becomes the Meta title
    .join('\n')
    // `<dialog>` in prose is an unclosed JSX tag; escape `<` outside code spans.
    .split('`')
    .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;')))
    .join('`')
    .replace(/\{/g, '&#123;')
    .replace(/\}/g, '&#125;');

  return `import { Meta } from '@storybook/addon-docs/blocks';

{/* Generated by scripts/generate-doc-pages.mjs — do not edit by hand. */}

<Meta title="${title}" />

# ${title.split('/').pop()}

${preamble}

${body}
`;
}

const pages = [
  {
    file: 'Conformance.mdx',
    title: 'Accessibility/ARIA conformance',
    markdown: run('audit-aria.mjs', ['src']),
    preamble: `> Generated by \`npm run aria\` on every build. The numbers below are the
> build's numbers, including the failures — a conformance page that shows no
> gaps is making a claim you cannot check.`,
  },
  {
    file: 'TokenDrift.mdx',
    title: 'Foundations/Token drift',
    markdown: run('audit-drift.mjs', ['src/styles']),
    preamble: `> Generated by \`npm run audit:drift\`. Eight value classes, every stylesheet
> the library ships. A literal that should be a token fails the build, so this
> page reading "clean" is an assertion rather than a claim.`,
  },
];

mkdirSync(OUT, { recursive: true });
let drifted = false;

for (const page of pages) {
  const content = toMdx(page.title, page.markdown, page.preamble);
  const target = resolve(OUT, page.file);

  if (CHECK) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (current !== content) {
      console.error(`docs/generated/${page.file} is out of date — run \`npm run docs:generate\`.`);
      drifted = true;
    }
    continue;
  }
  writeFileSync(target, content);
  console.log(`docs/generated/${page.file}  ${content.length} bytes`);
}

if (CHECK) {
  if (drifted) process.exit(1);
  console.log(`All ${pages.length} generated pages are in sync.`);
}
